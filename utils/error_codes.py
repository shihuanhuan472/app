class BizCode(IntEnum):
    SUCCESS = 1

    BAD_REQUEST = 40000
    UNAUTHORIZED = 40100
    FORBIDDEN = 40300
    NOT_FOUND = 40400
    INTERNAL_ERROR = 50000

    DOC_FILE_TYPE_UNSUPPORTED = 40010
    DOC_REQUEST_INVALID = 40011
    DOC_PARSE_FAILED = 40012
    DOC_TOKEN_LIMIT_EXCEEDED = 40013
    DOC_RESOURCE_NOT_FOUND = 40410
    AUTH_INVALID_CREDENTIALS = 40110
    AUTH_ROLE_INVALID = 40111
    AUTH_ROLE_MISMATCH = 40310
    AUTH_ACCOUNT_DISABLED = 40311
    USER_NOT_FOUND = 40420
    USER_DUPLICATE_PHONE = 40020
    USER_DUPLICATE_EMAIL = 40021
    USER_DUPLICATE_USERNAME = 40022
    REVIEW_ALREADY_PROCESSED = 40030
    REVIEW_LOCKED = 40900
    CONVERSATION_NOT_FOUND = 40430
    CONVERSATION_FORBIDDEN = 40330
    MESSAGE_CONTEXT_TOO_LONG = 40040
    AI_SERVICE_UNAVAILABLE = 50210


HTTP_TO_BIZ_CODE = {
    400: BizCode.BAD_REQUEST,
    401: BizCode.UNAUTHORIZED,
    403: BizCode.FORBIDDEN,
    404: BizCode.NOT_FOUND,
    500: BizCode.INTERNAL_ERROR,
    502: BizCode.AI_SERVICE_UNAVAILABLE,
}

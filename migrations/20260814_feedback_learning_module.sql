CREATE TABLE IF NOT EXISTS `user_reliability` (
  `user_id` INT NOT NULL,
  `total_feedback` INT NOT NULL DEFAULT 0,
  `verified_feedback` INT NOT NULL DEFAULT 0,
  `rejected_feedback` INT NOT NULL DEFAULT 0,
  `correction_feedback` INT NOT NULL DEFAULT 0,
  `correct_correction_count` INT NOT NULL DEFAULT 0,
  `reliability_score` FLOAT NOT NULL DEFAULT 0.5,
  `decay_factor` FLOAT NOT NULL DEFAULT 0.98,
  `recent_verified_weight` FLOAT NOT NULL DEFAULT 0,
  `recent_rejected_weight` FLOAT NOT NULL DEFAULT 0,
  `recent_correction_weight` FLOAT NOT NULL DEFAULT 0,
  `last_updated_at` DATETIME NULL,
  PRIMARY KEY (`user_id`),
  KEY `idx_user_reliability_score` (`reliability_score`),
  KEY `idx_user_reliability_last_updated` (`last_updated_at`)
);


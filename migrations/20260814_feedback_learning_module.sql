CREATE TABLE IF NOT EXISTS `feedback_records` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `conversation_id` INT NOT NULL,
  `message_id` INT NOT NULL,
  `user_id` INT NOT NULL,
  `feedback_type` VARCHAR(32) NOT NULL,
  `rating` INT NULL,
  `comment` TEXT NULL,
  `created_at` DATETIME NULL,
  `query_snapshot` MEDIUMTEXT NULL,
  `answer_snapshot` MEDIUMTEXT NULL,
  `retrieved_documents` MEDIUMTEXT NULL,
  `cited_documents` MEDIUMTEXT NULL,
  `trace_id` INT NULL,
  `status` VARCHAR(32) NOT NULL DEFAULT 'pending',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_feedback_records_conversation_message_user_type` (`conversation_id`, `message_id`, `user_id`, `feedback_type`),
  KEY `idx_feedback_records_conversation_id` (`conversation_id`),
  KEY `idx_feedback_records_message_id` (`message_id`),
  KEY `idx_feedback_records_user_id` (`user_id`),
  KEY `idx_feedback_records_trace_id` (`trace_id`),
  KEY `idx_feedback_records_type` (`feedback_type`),
  KEY `idx_feedback_records_status` (`status`),
  KEY `idx_feedback_records_created_at` (`created_at`)
);

CREATE TABLE IF NOT EXISTS `feedback_claims` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `feedback_id` INT NOT NULL,
  `claim_type` VARCHAR(64) NOT NULL,
  `subject` VARCHAR(255) NULL,
  `predicate` VARCHAR(128) NULL,
  `object` TEXT NULL,
  `scope` VARCHAR(255) NULL,
  `source` VARCHAR(32) NOT NULL DEFAULT 'user',
  `confidence` FLOAT NOT NULL DEFAULT 0,
  `verification_status` VARCHAR(32) NOT NULL DEFAULT 'unverified',
  `evidence_ids` MEDIUMTEXT NULL,
  `created_at` DATETIME NULL,
  PRIMARY KEY (`id`),
  KEY `idx_feedback_claims_feedback_id` (`feedback_id`),
  KEY `idx_feedback_claims_claim_type` (`claim_type`),
  KEY `idx_feedback_claims_subject` (`subject`),
  KEY `idx_feedback_claims_predicate` (`predicate`),
  KEY `idx_feedback_claims_scope` (`scope`),
  KEY `idx_feedback_claims_source` (`source`),
  KEY `idx_feedback_claims_verification_status` (`verification_status`),
  KEY `idx_feedback_claims_created_at` (`created_at`)
);


"""LoRA fine-tuning for the project's Visualized_BGE text encoder.

This script reads QA pairs generated by generate_qa_pairs.py. It trains the BGE
text encoder with in-batch contrastive learning:

    query = question
    positive = answer + source text

Only LoRA weights are trainable. The script can save both a small LoRA adapter
and a merged .pth file that can be used as MODEL_WEIGHT by this project.
"""

